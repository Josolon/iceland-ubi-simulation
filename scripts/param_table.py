"""Every parameter the model uses, with its value, where it comes from and how sure it is — read from the source.

    .venv/bin/python scripts/param_table.py            # writes docs/PARAMETERS.md and data/processed/parameters.json

The table is generated from src/ubisim/abm/params.py itself, so it cannot fall out of step with the model: each
entry carries the comment written beside it and the comment block above it. Status is read from those comments:

  DATA       a published figure (Hagstofa table, Skatturinn, Seðlabanki, OECD ...), named in the comment
  TUNED      set by fitting the 2016-2025 backcast (scripts/tune_backcast.py, tune_round2.py)
  CALIBRATED set inside the model so the status quo reproduces 2025 (behavioural constants, hazards)
  EST        an estimate: a judgement informed by the literature named, not a measurement
  POLICY     a setting of the reform, not a fact about the world
"""
import ast
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from ubisim.abm import params  # noqa: E402

SRC = ROOT / "src/ubisim/abm/params.py"
OUT_MD = ROOT / "docs/PARAMETERS.md"
OUT_JSON = ROOT / "data/processed/parameters.json"

POLICY_SECTIONS = {"policy"}
DATA_HINTS = re.compile(r"\b(THJ|VIN|MAN|TEK|LAU|SKO|SJA|LAN|FYR|UTA|LIF|FEL)\d{4,5}\b|Hagstofa|Skatturinn|"
                        r"Seðlabanki|OECD|HMS|Tryggingastofnun|World Bank|Hafró|Isavia|Eurostat|IMF|Landssamtök|"
                        r"Fiskistofa|Orkustofnun|Landsvirkjun|Rannís|UST")


def status_of(section, comment, context):
    text = f"{comment} {context}"
    if "TUNED" in comment:
        return "TUNED"
    if "CALIBRATED" in comment:
        return "CALIBRATED"
    if re.search(r"\bEST\b", comment):
        return "EST"
    if section in POLICY_SECTIONS:
        return "POLICY"
    if DATA_HINTS.search(comment):
        return "DATA"
    if re.search(r"\bEST\b", context):
        return "EST"
    if DATA_HINTS.search(text):
        return "DATA"
    return "EST"


def walk():
    """(section, key, line, comment, context) for every scalar entry in DEFAULTS, found in the source."""
    lines = SRC.read_text().split("\n")
    tree = ast.parse(SRC.read_text())
    target = next(n for n in ast.walk(tree) if isinstance(n, ast.Assign)
                  and any(getattr(t, "id", None) == "DEFAULTS" for t in n.targets))
    out = []

    def comment_on(lineno):
        l = lines[lineno - 1]
        i = l.find("#")
        return l[i + 1:].strip() if i >= 0 and '"' not in l[i:] else ""

    def block_above(lineno):
        block, j = [], lineno - 2
        while j >= 0 and lines[j].strip().startswith("#"):
            block.insert(0, lines[j].strip().lstrip("#").strip())
            j -= 1
        return " ".join(block)

    def visit(node, path):
        if not isinstance(node, ast.Dict):
            return
        for k, v in zip(node.keys, node.values):
            if not isinstance(k, ast.Constant):
                continue
            key = str(k.value)
            if isinstance(v, ast.Dict) and path and len(path) < 3 and v.keys and all(
                    isinstance(kk, ast.Constant) and isinstance(kk.value, str) for kk in v.keys):
                visit(v, path + [key])
                continue
            if isinstance(v, ast.Dict) and not path:
                visit(v, [key])
                continue
            out.append((path, key, k.lineno, comment_on(k.lineno), block_above(k.lineno)))

    visit(target.value, [])
    return out


def value_at(path, key):
    node = params.DEFAULTS
    for p_ in path:
        node = node[p_]
    return node[key]


def fmt(v):
    if isinstance(v, float):
        return f"{v:,.6g}"
    if isinstance(v, int) and not isinstance(v, bool):
        return f"{v:,}"
    s = json.dumps(v, ensure_ascii=False)
    return s if len(s) < 60 else s[:57] + "…"


def main():
    rows = []
    for path, key, lineno, comment, context in walk():
        try:
            v = value_at(path, key)
        except (KeyError, TypeError):
            continue
        section = path[0] if path else "(top)"
        rows.append({"section": ".".join(path) or "(top)", "key": key, "value": v if isinstance(
            v, (int, float, str, bool, type(None))) else json.loads(json.dumps(v, default=str)),
                     "status": status_of(section, comment, context), "note": comment, "context": context,
                     "line": lineno})
    OUT_JSON.write_text(json.dumps(rows, ensure_ascii=False, indent=0, default=str))
    counts = {}
    for r in rows:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    md = ["# Parameters", "",
          "Generated by `scripts/param_table.py` from `src/ubisim/abm/params.py`; do not edit by hand. "
          "Status: DATA a published figure; TUNED fitted to the 2016-2025 backcast; CALIBRATED set inside the "
          "model to reproduce 2025; EST an estimate informed by the literature named; POLICY a setting of the reform.",
          "", "Counts: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())), ""]
    for sec in dict.fromkeys(r["section"] for r in rows):
        md += [f"## {sec}", "", "| Parameter | Value | Status | Note |", "|---|---|---|---|"]
        for r in rows:
            if r["section"] != sec:
                continue
            note = (r["note"] or r["context"]).replace("|", "\\|")
            md.append(f"| `{r['key']}` | {fmt(r['value'])} | {r['status']} | {note[:300]} |")
        md.append("")
    OUT_MD.write_text("\n".join(md))
    print(f"{len(rows)} parameters: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))
    print(f"wrote {OUT_MD} and {OUT_JSON}")


if __name__ == "__main__":
    main()
